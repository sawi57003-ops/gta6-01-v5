// Boot and the one loop: input every frame, the world in fixed 1/60 s steps,
// then the renderer and the HUD. Screens: title, play, paused, busted,
// wasted, complete. ?seed=N fixes the city; ?shot=cover|chase|mission|street
// stages that scene instead of running the loop, paints it and sets
// window.__shotReady for a screenshot.
import { CITY_NAME, GAME_TITLE, PITCH, STORY, TUNING, WORLD, DEBT } from './config.js';
import { clamp, distance, mulberry32 } from './random.js';
import { buildCity, roadCenter } from './city.js';
import { ACTION_CONFIRM, ACTION_INTERACT, ACTION_PAUSE, ACTION_PUNCH, ACTION_SHOOT, ACTION_MISSIONS, createInput } from './input.js';
import { SoundEngine } from './audio.js';
import { Player } from './player.js';
import { Traffic } from './traffic.js';
import { Police } from './police.js';
import { MissionManager, MISSIONS } from './missions.js';
import { Camera, SCREEN_BUSTED, SCREEN_COMPLETE, SCREEN_PAUSED, SCREEN_PLAY, SCREEN_TITLE, SCREEN_WASTED, createRenderer } from './render.js';
import { drawHud } from './hud.js';
import { drawCar, makeCar } from './vehicles.js';
import { stageShot } from './shots.js';
import { CONTENT } from './content.js';

const STEP = 1 / 60;
const MAX_FRAME = 0.25;
const SAVE_KEY = 'neon-vice.save.v1';
const HOSPITAL = { x: 1 * PITCH + WORLD.road / 2, y: 1 * PITCH + WORLD.road / 2 };

const params = new URLSearchParams(window.location.search);
const shot = params.get('shot');
const seedParam = Number.parseInt(params.get('seed') ?? '', 10);
const seed = Number.isInteger(seedParam) ? seedParam : Math.floor(Math.random() * 4294967296);

const canvas = document.getElementById('game');
const status = document.getElementById('status');
const ctx = canvas.getContext('2d');

/** Build a fresh world: city, player, traffic, police, missions, pickups, parked cars. */
export function createWorld(worldSeed) {
  const rng = mulberry32(worldSeed ^ 0x9e3779b9);
  const city = buildCity(worldSeed);
  const player = new Player(roadCenter(3), roadCenter(3));
  const traffic = new Traffic(city, worldSeed);
  const police = new Police(city, worldSeed);
  const missions = new MissionManager();
  const sound = new SoundEngine();

  const world = {
    city,
    player,
    traffic,
    police,
    missions,
    sound,
    time: 0,
    particles: [],
    skids: [],
    pickups: [],
    parkedCars: [],
    toast: '',
    toastTimer: 0,
    nearMission: null,
    scare: false,
    bustedFlag: false,
    wastedFlag: false,
    freeRoam: false,
    best: null,
    // Content catalogue (generated by main.ts): a rotating story beat for the
    // title screen and the in-car radio station for the HUD.
    beat: CONTENT.beats[0],
    radio: CONTENT.radio[0],

    allCars() {
      const cars = [...traffic.cars, ...police.cars, ...this.parkedCars];
      if (player.car) cars.push(player.car);
      return cars;
    },

    showToast(text) {
      this.toast = text;
      this.toastTimer = 3;
    },

    addCashParticles(x, y) {
      for (let i = 0; i < 26; i += 1) {
        this.particles.push({
          x, y,
          vx: (rng() - 0.5) * 260,
          vy: (rng() - 0.5) * 260 - 60,
          life: 0.9,
          color: '#ffd34d',
        });
      }
    },

    onCrash(x, y) {
      this.sound.crash();
      this.traffic.scareNear(x, y, 320);
      for (let i = 0; i < 10; i += 1) {
        this.particles.push({
          x, y,
          vx: (rng() - 0.5) * 220,
          vy: (rng() - 0.5) * 220,
          life: 0.6,
          color: '#e8e4da',
        });
      }
    },

    spawnPickups() {
      // Cash, health and ammo scattered on roads and lots.
      for (let i = 0; i < 7; i += 1) {
        const p = city.randomOpenPoint();
        this.pickups.push({ x: p.x, y: p.y, kind: 'cash', amount: 250 + Math.floor(rng() * 400) });
      }
      for (let i = 0; i < 4; i += 1) {
        const p = city.randomOpenPoint();
        this.pickups.push({ x: p.x, y: p.y, kind: 'health' });
      }
      for (let i = 0; i < 4; i += 1) {
        const p = city.randomOpenPoint();
        this.pickups.push({ x: p.x, y: p.y, kind: 'ammo' });
      }
    },

    spawnParkedCars() {
      for (let i = 0; i < 9; i += 1) {
        const lot = city.parkingLots[Math.floor(rng() * city.parkingLots.length)];
        const x = lot ? lot.x0 + 30 + rng() * (lot.w - 60) : roadCenter(2) + rng() * 200;
        const y = lot ? lot.y0 + 30 + rng() * (lot.h - 60) : roadCenter(4);
        this.parkedCars.push(makeCar(x, y, rng() < 0.5 ? 0 : Math.PI / 2, {}));
      }
    },
  };

  world.spawnPickups();
  world.spawnParkedCars();
  return world;
}

function saveGame(world) {
  try {
    const data = {
      cash: world.player.cash,
      earned: world.missions.earned,
      completed: world.missions.completedCount,
      index: world.missions.index,
      health: world.player.health,
      ammo: world.player.ammo,
    };
    localStorage.setItem(SAVE_KEY, JSON.stringify(data));
  } catch (e) { /* storage unavailable; the game still runs */ }
}

function loadGame(world) {
  try {
    const raw = localStorage.getItem(SAVE_KEY);
    if (!raw) return;
    const data = JSON.parse(raw);
    if (typeof data.cash === 'number') world.player.cash = data.cash;
    if (typeof data.earned === 'number') world.missions.earned = data.earned;
    if (typeof data.completed === 'number') world.missions.completedCount = data.completed;
    if (typeof data.index === 'number' && data.index > 0 && data.index < MISSIONS.length) {
      world.missions.index = data.index;
    }
    if (typeof data.health === 'number') world.player.health = data.health;
    if (typeof data.ammo === 'number') world.player.ammo = data.ammo;
    if (world.missions.completedCount > 0) {
      world.best = '$' + world.player.cash.toLocaleString('en-US') + ' earned, ' + world.missions.completedCount + '/6 jobs';
    }
  } catch (e) { /* corrupt save; start fresh */ }
}

const world = createWorld(seed);
loadGame(world);
const input = createInput();
input.attach();
const renderer = createRenderer(canvas);
const camera = new Camera();

let screen = SCREEN_TITLE;
let last = performance.now();
let accumulator = 0;
let paused = false;
let screenTimer = 0;

function announce(text) {
  if (status) status.textContent = text;
}

function startMission() {
  const m = world.missions.current();
  if (!m) return;
  world.missions.start();
  world.sound.missionStart();
  world.showToast('Job started: ' + m.title + ' — ' + m.brief);
  announce('Job started: ' + m.title);
}

function update(dt) {
  world.time += dt;
  // Rotate the title-screen beat and the radio station from the catalogue.
  world.beat = CONTENT.beats[Math.floor(world.time / 6) % CONTENT.beats.length];
  world.radio = CONTENT.radio[Math.floor(world.time / 24) % CONTENT.radio.length];
  const player = world.player;

  if (screen === SCREEN_TITLE) {
    if (input.wasPressed(ACTION_CONFIRM)) {
      world.sound.ensure();
      screen = SCREEN_PLAY;
      announce('Playing. ' + STORY);
      if (!world.missions.active && !world.missions.done) startMission();
    }
    return;
  }
  if (screen === SCREEN_PAUSED) {
    if (input.wasPressed(ACTION_PAUSE) || input.wasPressed(ACTION_CONFIRM)) {
      screen = SCREEN_PLAY;
      paused = false;
    }
    return;
  }
  if (screen === SCREEN_BUSTED || screen === SCREEN_WASTED || screen === SCREEN_COMPLETE) {
    screenTimer -= dt;
    if (screenTimer <= 0 && input.wasPressed(ACTION_CONFIRM)) {
      if (screen === SCREEN_COMPLETE) {
        screen = SCREEN_PLAY;
        world.freeRoam = true;
      } else {
        // Respawn at the hospital, keep the cash, lose the heat.
        player.health = TUNING.playerHealth;
        player.wanted = 0;
        player.x = HOSPITAL.x;
        player.y = HOSPITAL.y;
        if (player.car) player.car = null;
        world.bustedFlag = false;
        world.wastedFlag = false;
        screen = SCREEN_PLAY;
        announce('Back on the streets.');
      }
    }
    return;
  }

  // --- Play.
  if (input.wasPressed(ACTION_PAUSE)) {
    screen = SCREEN_PAUSED;
    paused = true;
    return;
  }
  if (input.wasPressed(ACTION_MISSIONS)) {
    const m = world.missions.current();
    if (m) world.showToast((world.missions.active ? 'Current job: ' : 'Next job: ') + m.title + ' — ' + m.brief);
    return;
  }

  player.update(dt, input, world.city, world);
  world.traffic.update(dt, player, world);
  world.police.update(dt, player, world);

  // Engine hum.
  world.sound.engine(player.car ? Math.abs(player.car.speed) / TUNING.carMaxSpeed : 0);

  // Skid marks when the car turns hard at speed.
  if (player.car && Math.abs(player.car.speed) > 300) {
    const mv = input.moveVector();
    if (mv.x !== 0 && world.skids.length < 240) {
      world.skids.push({
        x1: player.car.x, y1: player.car.y,
        x2: player.car.x - Math.cos(player.car.angle) * 26,
        y2: player.car.y - Math.sin(player.car.angle) * 26,
      });
    }
  }

  // Interact: get in/out of a car, or start the next job at the marker.
  if (input.wasPressed(ACTION_INTERACT)) {
    world.sound.ensure();
    if (player.car) {
      player.exitCar();
      world.sound.click();
    } else {
      const car = player.nearestCar(world.allCars());
      if (car) {
        // Stealing a car in front of a cop, or a police car, draws heat.
        const isPoliceCar = car.kind === 'police';
        const nearCop = world.police.cars.some((c) => distance(c.x, c.y, player.x, player.y) < 420);
        player.enterCar(car);
        world.traffic.cars = world.traffic.cars.filter((c) => c !== car);
        world.parkedCars = world.parkedCars.filter((c) => c !== car);
        world.police.cars = world.police.cars.filter((c) => c !== car);
        if (isPoliceCar) player.addWanted(2);
        else if (nearCop) player.addWanted(1);
        else if (world.traffic.peds.some((p) => distance(p.x, p.y, player.x, player.y) < 200)) player.addWanted(1);
        world.sound.click();
      } else if (!world.missions.active && !world.missions.done) {
        startMission();
      }
    }
  }

  // Punch.
  if (input.wasPressed(ACTION_PUNCH) && !player.car) {
    const targets = [
      ...world.traffic.peds,
      ...world.police.officers,
    ];
    const hit = player.punch(targets);
    if (hit) {
      world.sound.punch();
      world.traffic.scareNear(player.x, player.y, 300);
      if (world.police.officers.includes(hit)) {
        player.addWanted(2);
      } else if (Math.random() < 0.6) {
        player.addWanted(1);
      }
      // A punched pedestrian drops cash.
      if (world.traffic.peds.includes(hit)) {
        world.pickups.push({ x: hit.x, y: hit.y, kind: 'cash', amount: 40 + Math.floor(Math.random() * 80) });
        hit.flee = 2;
        hit.angle = Math.atan2(hit.y - player.y, hit.x - player.x);
      }
    }
  }

  // Shoot.
  if (input.wasPressed(ACTION_SHOOT) && !player.car) {
    if (player.shoot()) {
      world.sound.shoot();
      world.traffic.scareNear(player.x, player.y, 420);
      // Hit the nearest cop or pedestrian in the firing line.
      const fx = Math.cos(player.angle);
      const fy = Math.sin(player.angle);
      let best = null;
      let bestD = TUNING.pistolRange;
      const candidates = [...world.police.officers, ...world.police.cars, ...world.traffic.peds];
      for (const t of candidates) {
        const dx = t.x - player.x;
        const dy = t.y - player.y;
        const along = dx * fx + dy * fy;
        const side = Math.abs(dx * -fy + dy * fx);
        if (along > 0 && along < bestD && side < 34) {
          bestD = along;
          best = t;
        }
      }
      if (best) {
        if (world.police.officers.includes(best)) {
          world.police.officers = world.police.officers.filter((o) => o !== best);
          player.addWanted(2);
        } else if (world.police.cars.includes(best)) {
          best.health -= TUNING.pistolDamage;
          player.addWanted(1);
        } else {
          best.flee = 2.5;
          player.addWanted(1);
        }
      } else if (Math.random() < 0.5) {
        player.addWanted(1);
      }
    }
  }

  // Mission step: reach the marker, or the steal condition.
  const step = world.missions.currentStep();
  if (world.missions.active && step) {
    let reached = false;
    if (step.kind === 'steal') {
      reached = world.missions.checkSteal(player);
    } else {
      const d = distance(player.x, player.y, step.x, step.y);
      const needCar = !!step.needsCar;
      reached = d < 58 && (!needCar || !!player.car);
    }
    if (reached) {
      const result = world.missions.advance(world);
      if (result === 'step') {
        world.sound.pickup();
        world.addCashParticles(player.x, player.y);
        const next = world.missions.currentStep();
        if (next) world.showToast(next.label);
      } else if (result === 'mission') {
        world.sound.missionDone();
        world.addCashParticles(player.x, player.y);
        const m = world.missions.current();
        world.showToast('Job done! +$' + MISSIONS[world.missions.index - 1].reward.toLocaleString('en-US') + '. Next: ' + (m ? m.title : '—'));
        announce('Job complete.');
        saveGame(world);
      } else if (result === 'all') {
        world.sound.missionDone();
        world.addCashParticles(player.x, player.y);
        screen = SCREEN_COMPLETE;
        screenTimer = 0.6;
        world.best = '$' + player.cash.toLocaleString('en-US') + ' earned, 6/6 jobs';
        announce('All six jobs done. The debt is paid.');
        saveGame(world);
      }
      // A step that demands heat applies it on arrival.
      const arrived = world.missions.currentStep();
      if (arrived && arrived.wanted) player.addWanted(1);
    }
  }
  // The step's wanted level: arriving at a hot step raises heat.
  if (world.missions.active && step && step.wanted) {
    const d = distance(player.x, player.y, step.x, step.y);
    if (d < 200 && player.wanted < step.wanted) player.wanted = step.wanted;
  }

  // Pickups.
  for (let i = world.pickups.length - 1; i >= 0; i -= 1) {
    const pk = world.pickups[i];
    if (distance(player.x, player.y, pk.x, pk.y) < 34) {
      if (pk.kind === 'cash') {
        player.addCash(pk.amount);
        world.sound.cash();
        world.addCashParticles(pk.x, pk.y);
        world.showToast('+$' + pk.amount);
      } else if (pk.kind === 'health') {
        player.health = Math.min(TUNING.playerHealth, player.health + 35);
        world.sound.pickup();
        world.showToast('Health +35');
      } else {
        player.ammo += 18;
        world.sound.pickup();
        world.showToast('Ammo +18');
      }
      world.pickups.splice(i, 1);
    }
  }

  // Particles.
  for (let i = world.particles.length - 1; i >= 0; i -= 1) {
    const pt = world.particles[i];
    pt.life -= dt;
    pt.x += pt.vx * dt;
    pt.y += pt.vy * dt;
    pt.vy += 260 * dt;
    if (pt.life <= 0) world.particles.splice(i, 1);
  }
  if (world.skids.length > 240) world.skids.splice(0, world.skids.length - 240);

  // Toast timer.
  if (world.toastTimer > 0) world.toastTimer -= dt;

  // Busted / wasted.
  if (world.bustedFlag) {
    world.bustedFlag = false;
    world.sound.busted();
    screen = SCREEN_BUSTED;
    screenTimer = 0.6;
    announce('Busted by the Vice Bay PD.');
    saveGame(world);
  }
  if (player.health <= 0 && !world.wastedFlag) {
    world.wastedFlag = true;
    world.sound.wasted();
    screen = SCREEN_WASTED;
    screenTimer = 0.6;
    announce('Wasted.');
    saveGame(world);
  }

  // Camera follows the player.
  camera.follow(player.x, player.y, player.car ? Math.abs(player.car.speed) : 0, renderer.vw, renderer.vh, dt);
}

function frame(now) {
  requestAnimationFrame(frame);
  const elapsed = Math.min(MAX_FRAME, (now - last) / 1000);
  last = now;
  if (shot) {
    // A staged screenshot: paint once, do not run the loop.
    renderer.drawWorld(world, camera, world.time);
    return;
  }
  accumulator += elapsed;
  while (accumulator >= STEP) {
    update(STEP);
    accumulator -= STEP;
    input.endFrame();
  }
  // Render the current screen.
  if (screen === SCREEN_TITLE) {
    // A slow pan over the city behind the title.
    camera.x = (Math.sin(world.time * 0.02) * 0.5 + 0.5) * (WORLD.size - renderer.vw);
    camera.y = 300 + Math.sin(world.time * 0.013) * 160;
    camera.zoom = 0.62;
    renderer.drawWorld(world, camera, world.time);
    renderer.drawTitle(world, world.time);
  } else if (screen === SCREEN_PLAY) {
    renderer.drawWorld(world, camera, world.time);
    drawHud(ctx, world, renderer.vw, renderer.vh, world.time);
  } else if (screen === SCREEN_PAUSED) {
    renderer.drawWorld(world, camera, world.time);
    drawHud(ctx, world, renderer.vw, renderer.vh, world.time);
    renderer.drawOverlay('PAUSED', 'Take a breath, Vic.', 'Press P or ENTER to keep driving.  M — jobs.  Progress is saved.');
  } else if (screen === SCREEN_BUSTED) {
    renderer.drawWorld(world, camera, world.time);
    renderer.drawOverlay('BUSTED', 'The Vice Bay PD has you.', 'Press ENTER to wake up at the hospital. Your cash stays — the heat does not.');
  } else if (screen === SCREEN_WASTED) {
    renderer.drawWorld(world, camera, world.time);
    renderer.drawOverlay('WASTED', 'Vice Bay is not done with you yet.', 'Press ENTER to wake up at the hospital.');
  } else if (screen === SCREEN_COMPLETE) {
    renderer.drawWorld(world, camera, world.time);
    renderer.drawOverlay(
      'DEBT PAID',
      'All six jobs done — the Sunset Kings are settled. $' + world.player.cash.toLocaleString('en-US') + ' earned.',
      'Press ENTER for free roam. The bay is yours now.',
    );
  }
  input.endFrame();
}

if (shot) {
  // Stage the scene, centre the camera on the player, paint once.
  world.missions.active = true;
  stageShot(world, shot);
  const player = world.player;
  camera.x = player.x - renderer.vw / 2;
  camera.y = player.y - renderer.vh / 2;
  camera.zoom = 1;
  renderer.drawWorld(world, camera, 1.2);
  drawHud(ctx, world, renderer.vw, renderer.vh, 1.2);
  window.__shotReady = true;
} else {
  requestAnimationFrame(frame);
}
